TOPE = -(-len(BASE_CI) * 11 // 10)  # ceil(1493 * 1,1) = 1643

_CODIGO = "\n".join((
    "import json, sys",
    # -I ignora PYTHONPATH y quita el directorio actual de sys.path: la raíz se añade a mano para poder importar main.
    "sys.path.insert(0, {raiz!r})",
    "{previo}",
    "import main",
    "print(json.dumps(sorted(sys.modules)))",
))


def _entorno() -> dict:
    """R3: el entorno del arnés tal cual."""
    return dict(os.environ)


def _modulos_tras_importar_main(previo: str = "") -> list[str]:
    """Lanza `python -X importtime -I` e imprime sys.modules desde el subproceso (no se lee la salida de importtime)."""
    codigo = _CODIGO.format(raiz=str(RAIZ), previo=previo)
    r = subprocess.run([sys.executable, "-X", "importtime", "-I", "-c", codigo], cwd=RAIZ, env=_entorno(),
                       capture_output=True, text=True, timeout=180)
    assert r.returncode == 0, f"import main falló: {r.stderr[-2000:]}"
    return json.loads(r.stdout.strip().splitlines()[-1])


@lru_cache(maxsize=None)
def _arranque_real() -> tuple[str, ...]:
    _modulos_tras_importar_main()  # primera vez: se escriben los .pyc
    return tuple(_modulos_tras_importar_main())


def _prohibidas_cargadas(modulos) -> list[str]:
    conjunto = set(modulos)
    return sorted(p for p in PROHIBIDAS if p in conjunto or any(m.startswith(p + ".") for m in conjunto))


def _informe_de_exceso(modulos) -> str:
    nuevos = sorted(set(modulos) - BASE_CI)
    return f"import main carga {len(modulos)} módulos, tope {TOPE}. Módulos nuevos respecto a la línea base ({len(nuevos)}): {nuevos}"


def test_r1_main_arranca_sin_pandas_openpyxl_ni_fpdf():
    cargadas = _prohibidas_cargadas(_arranque_real())
    assert cargadas == [], f"import main carga {cargadas}: impórtalas dentro de la función"


def test_r2_import_main_queda_bajo_el_tope_de_modulos():
    modulos = _arranque_real()
    assert len(modulos) <= TOPE, _informe_de_exceso(modulos)


def test_m1_un_import_pandas_al_arrancar_da_rojo_en_r1():
    _arranque_real()
    modulos = _modulos_tras_importar_main("import pandas")
    assert "pandas" in _prohibidas_cargadas(modulos), "m1: el detector de R1 debe ver pandas cargado"


def test_m2_una_libreria_pesada_nueva_al_arrancar_supera_el_tope_de_r2():
    _arranque_real()
    modulos = _modulos_tras_importar_main("import pandas")
    assert len(modulos) > TOPE, f"m2: pandas debe superar el tope ({len(modulos)} <= {TOPE})"
    assert "pandas" in _informe_de_exceso(modulos), "m2: el rojo debe listar los módulos nuevos"
